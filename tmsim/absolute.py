"""Предварительная проверка на абсолютные основания для отказа
(признаки охраноспособности, ст. 6 Закона РК о товарных знаках).
Это подсказки для эксперта, а не заключение."""
from __future__ import annotations

from .text_sim import clean, stem, tokens

STATE_SYMBOLS = {"герб", "флаг", "гимн", "республика", "республикасы", "государственный",
                 "мемлекеттік", "president", "президент", "елтаңба", "ту", "coat", "flag",
                 "national", "национальный", "ұлттық", "official", "официальный"}
INTL_ORGS = {"оон", "un", "unesco", "юнеско", "who", "воз", "нато", "nato", "олимп",
             "olympic", "олимпийский", "fifa", "фифа", "red cross", "красный крест",
             "қызыл крест", "interpol", "интерпол", "снг", "eaэс", "еаэс", "ес", "eu"}
GEO = {"казахстан", "қазақстан", "kazakhstan", "qazaqstan", "алматы", "almaty", "астана",
       "astana", "шымкент", "караганда", "кз", "kz"}
ALCOHOL = {"водка", "vodka", "коньяк", "cognac", "бренди", "brandy", "виски", "whisky",
           "whiskey", "вино", "wine", "шампанское", "champagne", "ром", "rum", "джин", "gin",
           "текила", "tequila", "пиво", "beer", "бальзам"}
PDO = {"champagne", "шампанское", "cognac", "коньяк", "tequila", "текила", "parmesan",
       "пармезан", "roquefort", "рокфор", "porto", "портвейн", "scotch", "скотч"}
DESCRIPTIVE = {"лучший", "best", "№1", "номер", "первый", "самый", "качественный",
               "quality", "натуральный", "natural", "оригинальный", "original", "эко", "eco",
               "био", "bio", "свежий", "fresh", "дешевый", "cheap"}
IMMORAL = {"бля", "хуй", "fuck", "shit", "наркот", "drug", "cocaine", "кокаин", "героин",
           "гитлер", "hitler", "нацист", "nazi", "террор", "terror", "игил", "isis"}
CULTURE = {"байтерек", "бәйтерек", "хан шатыр", "хазрет султан", "яссауи", "ясауи",
           "тамгалы", "абай", "аль-фараби", "фараби", "медеу", "чарын"}


def check(text: str, classes: list[int] | None = None) -> list[dict]:
    t = clean(text)
    toks = set(tokens(text))
    stems = {stem(x) for x in toks}
    classes = classes or []
    hits = []

    def has(words):
        found = [w for w in words if (" " in w and w in t) or w in toks or stem(w) in stems]
        return found

    if f := has(STATE_SYMBOLS):
        hits.append({"level": "warn", "ground": "Государственная символика",
                     "text": f"Слова, связанные с госсимволикой/официальными названиями: {', '.join(f)}. Изображения флагов и гербов, их имитация не допускаются."})
    if f := has(INTL_ORGS):
        hits.append({"level": "warn", "ground": "Международные организации",
                     "text": f"Названия/аббревиатуры международных организаций: {', '.join(f)} — регистрация только с их согласия."})
    if f := has(GEO):
        hits.append({"level": "info", "ground": "Географическое название",
                     "text": f"Географические названия ({', '.join(f)}) обычно признаются неохраняемым элементом; могут вводить в заблуждение о месте происхождения."})
    if f := has(ALCOHOL):
        if not set(classes) & {32, 33}:
            hits.append({"level": "warn", "ground": "Алкогольные напитки / введение в заблуждение",
                         "text": f"Обозначение содержит названия алкогольных напитков ({', '.join(f)}), а классы 32/33 не заявлены — возможно введение в заблуждение."})
    if f := has(PDO):
        hits.append({"level": "warn", "ground": "Наименование места происхождения",
                     "text": f"{', '.join(f)} — охраняемые наименования мест происхождения, не регистрируются для иных товаров."})
    if f := has(DESCRIPTIVE):
        hits.append({"level": "info", "ground": "Описательный/хвалебный характер",
                     "text": f"Элементы {', '.join(f)} указывают на качество/свойства и, как правило, неохраняемы."})
    if any(w in t for w in IMMORAL):
        hits.append({"level": "error", "ground": "Противоречие общественным интересам и принципам гуманности и морали",
                     "text": "Обозначение содержит слова, противоречащие общественному порядку или морали."})
    if f := has(CULTURE):
        hits.append({"level": "warn", "ground": "Объекты культурного наследия",
                     "text": f"Официальные названия/изображения объектов культурного наследия ({', '.join(f)}) регистрируются только с согласия собственника."})
    letters = t.replace(" ", "")
    if 0 < len(letters) <= 2:
        hits.append({"level": "warn", "ground": "Отсутствие различительной способности",
                     "text": "Отдельные буквы/сочетания из 1–2 букв без особого графического исполнения обычно не обладают различительной способностью."})
    if letters.isdigit():
        hits.append({"level": "warn", "ground": "Отсутствие различительной способности",
                     "text": "Обозначение состоит только из цифр."})
    return hits
