def class_relation(a: int, b: int) -> str:
    if a == b:
        return "same"
    for g in RELATED_GROUPS:
        if a in g and b in g:
            return "related"
    if 35 in (a, b):
        # услуги розничной/оптовой торговли однородны многим товарам
        other = b if a == 35 else a
        if other <= 34:
            return "retail_35"
    return "unrelated"


def class_similarity(ca: list[int], cb: list[int], w: dict) -> tuple[float, list[str], dict]:
    """Однородность по классам: берётся наиболее близкая пара классов."""
    if not ca or not cb:
        return w.get("same", 1.0), ["Классы МКТУ не указаны — однородность не учитывалась"], {}
    best, best_pair, rel = -1.0, None, "unrelated"
    for x in ca:
        for y in cb:
            r = class_relation(x, y)
            v = w.get(r, 0.1)
            if v > best:
                best, best_pair, rel = v, (x, y), r
    common = sorted(set(ca) & set(cb))
    names = {"same": "совпадающие классы", "related": "смежные (однородные) классы",
             "retail_35": "35 класс (торговля) и товары", "unrelated": "неоднородные классы"}
    det = [f"{names[rel].capitalize()}: {best_pair[0]} ↔ {best_pair[1]}"]
    if common:
        det = [f"Совпадающие классы МКТУ: {', '.join(map(str, common))}"]
    return best, det, {"relation": rel, "common": common}


def expand_classes(classes: list[int], include_related: bool = True) -> list[int]:
    """Классы, в которых нужно искать противопоставляемые знаки."""
    out = set(classes)
    if include_related:
        for c in classes:
            for g in RELATED_GROUPS:
                if c in g:
                    out |= g
            if c <= 34:
                out.add(35)
            if c == 35:
                out |= set(range(1, 35))
    return sorted(out)


def goods_overlap(ga: str | None, gb: str | None) -> float | None:
    """Пересечение перечней товаров/услуг (по основам слов)."""
    if not ga or not gb:
        return None
    from .text_sim import stem, tokens, STOP_WORDS
    sa = {stem(t) for t in tokens(ga) if len(t) > 3 and t not in STOP_WORDS}
    sb = {stem(t) for t in tokens(gb) if len(t) > 3 and t not in STOP_WORDS}
    if not sa or not sb:
        return None
    return len(sa & sb) / min(len(sa), len(sb))
